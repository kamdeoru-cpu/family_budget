"""Ошибки бизнес-логики, которые показываются пользователю."""


class ValidationError(Exception):
    """Пользователь ввёл некорректное значение (пустое поле, неверный формат)."""


class BusinessRuleError(Exception):
    """Действие запрещено правилами задачи (например, удалить используемую категорию)."""
